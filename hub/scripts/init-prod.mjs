// Creates hub/.env.prod for a pilot hub with fresh random secrets. Refuses to overwrite.
// Usage: node hub/scripts/init-prod.mjs --phone +919812345678 [--name "Ravi Kumar"] [--site "Sharma Residence"]
//        [--city Pune --state Maharashtra --lat 18.5204 --lng 73.8567] [--type villa]
import { randomBytes } from 'node:crypto';
import { existsSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseArgs } from 'node:util';

const { values: a } = parseArgs({
  options: {
    phone: { type: 'string' },
    name: { type: 'string', default: 'Owner' },
    site: { type: 'string', default: 'My Home' },
    type: { type: 'string', default: 'independent_house' },
    city: { type: 'string', default: 'Bengaluru' },
    state: { type: 'string', default: 'Karnataka' },
    lat: { type: 'string', default: '12.9716' },
    lng: { type: 'string', default: '77.5946' },
  },
});
if (!a.phone || !/^\+[1-9]\d{7,14}$/.test(a.phone)) {
  console.error('Give the owner phone in international format: --phone +919812345678');
  process.exit(1);
}

const file = join(dirname(fileURLToPath(import.meta.url)), '..', '.env.prod');
if (existsSync(file)) {
  console.error('hub/.env.prod already exists. Delete it first if you really want new secrets (boards and logins will break).');
  process.exit(1);
}

const secret = (n) => randomBytes(n).toString('base64url');
const ownerPassword = secret(12);
const q = (v) => `"${String(v).replaceAll('"', '')}"`;
writeFileSync(
  file,
  [
    '# Pilot hub settings. Generated by hub/scripts/init-prod.mjs. Keep this file private.',
    'NODE_ENV=production',
    'TZ=Asia/Kolkata',
    'DATABASE_URL="file:/data/db/hub.db"',
    'PORT=8080',
    'TRUST_PROXY=true',
    'BACKUP_DIR=/data/backups',
    'MQTT_URL="mqtt://mosquitto:1883"',
    `JWT_SECRET=${q(secret(48))}`,
    'ACCESS_TOKEN_TTL="15m"',
    'REFRESH_TOKEN_DAYS=30',
    'MQTT_ADMIN_USER="hub-backend"',
    `MQTT_ADMIN_PASSWORD=${q(secret(24))}`,
    `MQTT_BOOTSTRAP_PASSWORD=${q(secret(24))}`,
    'DEV_AUTO_APPROVE_SITE=""',
    '# First owner and site (used once, on an empty database)',
    'SEED_SITE_ID="home"',
    `SEED_SITE_NAME=${q(a.site)}`,
    `SEED_SITE_TYPE=${q(a.type)}`,
    `SEED_SITE_CITY=${q(a.city)}`,
    `SEED_SITE_STATE=${q(a.state)}`,
    `SEED_SITE_LAT=${Number(a.lat)}`,
    `SEED_SITE_LNG=${Number(a.lng)}`,
    `SEED_ADMIN_NAME=${q(a.name)}`,
    `SEED_ADMIN_PHONE=${q(a.phone)}`,
    `SEED_ADMIN_PASSWORD=${q(ownerPassword)}`,
    '',
  ].join('\n'),
  { mode: 0o600 },
);
console.log('Created hub/.env.prod');
console.log(`Owner sign-in: ${a.phone} / ${ownerPassword}`);
console.log('Write this password down now; it is also in hub/.env.prod (SEED_ADMIN_PASSWORD).');
